export function getLocationCoordinates(
  district: string,
  location: string,
): { lat: number; lng: number } {
  if (location && LOCATION_COORDINATES[location]) {
    return LOCATION_COORDINATES[location];
  }
  const districtLocs = DISTRICTS[district];
  if (districtLocs && districtLocs.length > 0) {
    for (const loc of districtLocs) {
      if (LOCATION_COORDINATES[loc]) {
        return LOCATION_COORDINATES[loc];
      }
    }
  }
  // Default coordinates (Assam center)
  return { lat: 26.2006, lng: 92.9376 };
}
